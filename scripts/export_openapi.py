"""Write the OpenAPI contract generated from the code to openapi.yaml.

Usage: python scripts/export_openapi.py [--check]
With --check the script exits non-zero if openapi.yaml is out of date.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

from pbx_api.app import create_app
from pbx_api.config import Config
from pbx_api.service import PbxService

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "openapi.yaml"
HEADER = "# Generated by scripts/export_openapi.py - do not edit by hand.\n"


def render() -> str:
    app = create_app(PbxService(Config(), store=None))  # type: ignore[arg-type]
    spec = app.openapi()
    return HEADER + yaml.safe_dump(spec, sort_keys=True, allow_unicode=True, width=100)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print("openapi.yaml is out of date; run scripts/export_openapi.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
